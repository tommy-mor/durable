impl<T: Serialize + DeserializeOwned + 'static> Path<Leaf<T>> {
    /// Read the value at this leaf, if present.
    pub fn get(&self, r: &impl Read) -> Result<Option<T>> {
        let (table, key) = self.table_and_prefix();
        match r.raw_get(table, key)? {
            Some(bytes) => Ok(Some(decode_value(&bytes)?)),
            None => Ok(None),
        }
    }

    /// Write `value` to this leaf inside `tx`.
    pub fn set(&self, tx: &mut Tx, value: &T) -> Result<()> {
        let (table, key) = self.table_and_prefix();
        let bytes = encode_value(value)?;
        tx.raw_put(table, key, &bytes)
    }

    /// Delete this leaf inside `tx`. Returns `true` if a value existed.
    pub fn delete(&self, tx: &mut Tx) -> Result<bool> {
        let (table, key) = self.table_and_prefix();
        tx.raw_delete(table, key)
    }

    /// Read-modify-write this leaf inside `tx`: `Some(v)` sets, `None` deletes.
    pub fn update(&self, tx: &mut Tx, f: impl FnOnce(Option<T>) -> Option<T>) -> Result<()> {
        let cur = self.get(tx)?;
        match f(cur) {
            Some(next) => self.set(tx, &next),
            None => {
                self.delete(tx)?;
                Ok(())
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Sum<N>
// ---------------------------------------------------------------------------

impl<N: Summable> Path<Sum<N>> {
    /// Read the accumulated value (returns zero when absent).
    pub fn get(&self, r: &impl Read) -> Result<N> {
        let (table, key) = self.table_and_prefix();
        match r.raw_get(table, key)? {
            Some(bytes) => decode_sum::<N>(&bytes)
                .ok_or_else(|| Error::Corruption("malformed Sum accumulator".into())),
            None => Ok(N::zero()),
        }
    }

    /// Add `delta` to the accumulator inside `tx`, returning the new total.
    pub fn add(&self, tx: &mut Tx, delta: N) -> Result<N> {
        let cur = self.get(tx)?;
        let next = cur.combine(delta);
        self.set(tx, next)?;
        Ok(next)
    }

    /// Set the accumulator to an exact value inside `tx`.
    pub fn set(&self, tx: &mut Tx, value: N) -> Result<()> {
        let (table, key) = self.table_and_prefix();
        tx.raw_put(table, key, &encode_sum(value))
    }

    /// Remove the accumulator inside `tx`. Returns `true` if it existed.
    pub fn delete(&self, tx: &mut Tx) -> Result<bool> {
        let (table, key) = self.table_and_prefix();
        tx.raw_delete(table, key)
    }
}

