impl<T: Serialize + DeserializeOwned + 'static> Path<List<Leaf<T>>> {
    /// Number of elements (O(1) at root; one reverse seek when nested).
    pub fn len(&self, r: &impl Read) -> Result<u64> {
        let (table, prefix) = self.table_and_prefix();
        if prefix.is_empty() {
            return r.raw_table_len(table);
        }
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_last_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (idx, _) = u64::decode_key(&db_key[scan.len()..])?;
                Ok(idx + 1)
            }
            None => Ok(0),
        }
    }

    /// Read the element at `index`.
    pub fn get(&self, r: &impl Read, index: u64) -> Result<Option<T>> {
        self.at(index).get(r)
    }

    /// First element (one seek).
    pub fn first(&self, r: &impl Read) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_first_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Last element (one reverse seek).
    pub fn last(&self, r: &impl Read) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_last_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Append `value` inside `tx`, returning its assigned index.
    pub fn push(&self, tx: &mut Tx, value: &T) -> Result<u64> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        let next_idx = match tx.raw_last_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (idx, _) = u64::decode_key(&db_key[scan.len()..])?;
                idx + 1
            }
            None => 0,
        };
        self.at(next_idx).set(tx, value)?;
        Ok(next_idx)
    }

    /// Remove and return the last element inside `tx`.
    pub fn pop(&self, tx: &mut Tx) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match tx.raw_pop_last_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Lazy, double-ended iterator over elements in index `range`.
    pub fn range(&self, r: &impl Read, range: impl KeyRange<u64>) -> Result<SeqIter<T>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let Some((lo, hi)) = range.to_byte_bounds(&scan) else {
            return Ok(SeqIter::empty());
        };
        let inner = r.raw_range(table, lo, hi)?;
        Ok(SeqIter {
            inner,
            _marker: PhantomData,
        })
    }

    /// All elements in index order (single streaming range scan).
    pub fn iter(&self, r: &impl Read) -> Result<Vec<T>> {
        self.range(r, ..)?.collect()
    }
}

