impl<K: Key, T: Serialize + DeserializeOwned + 'static> Path<Map<K, Leaf<T>>> {
    /// Read the value stored under `key`.
    pub fn get(&self, r: &impl Read, key: impl KeyLookup<K>) -> Result<Option<T>> {
        self.key(key).get(r)
    }

    /// Batch point-lookup over one snapshot (`r`), preserving input order.
    pub fn get_many<Q: KeyLookup<K>>(
        &self,
        r: &impl Read,
        keys: impl IntoIterator<Item = Q>,
    ) -> Result<Vec<Option<T>>> {
        let mut out = Vec::new();
        for k in keys {
            out.push(self.get(r, k)?);
        }
        Ok(out)
    }

    /// Set `key` to `value` inside `tx` (shorthand for `self.key(key).set(tx, value)`).
    pub fn set(&self, tx: &mut Tx, key: impl KeyLookup<K>, value: &T) -> Result<()> {
        self.key(key).set(tx, value)
    }

    /// Smallest `(key, value)` entry in the map (one seek).
    pub fn first_entry(&self, r: &impl Read) -> Result<Option<(K, T)>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_first_in(table, lo, hi)? {
            Some((db_key, db_val)) => {
                let rest = &db_key[scan.len()..];
                let (k, used) = K::decode_key(rest)?;
                if used != rest.len() {
                    return Err(Error::Corruption("unexpected nested key in leaf map".into()));
                }
                Ok(Some((k, decode_value(&db_val)?)))
            }
            None => Ok(None),
        }
    }

    /// Largest `(key, value)` entry in the map (one reverse seek).
    pub fn last_entry(&self, r: &impl Read) -> Result<Option<(K, T)>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_last_in(table, lo, hi)? {
            Some((db_key, db_val)) => {
                let rest = &db_key[scan.len()..];
                let (k, used) = K::decode_key(rest)?;
                if used != rest.len() {
                    return Err(Error::Corruption("unexpected nested key in leaf map".into()));
                }
                Ok(Some((k, decode_value(&db_val)?)))
            }
            None => Ok(None),
        }
    }

    /// Lazy, double-ended iterator over `(key, value)` pairs in `range`.
    pub fn range(&self, r: &impl Read, range: impl KeyRange<K>) -> Result<MapIter<K, T>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let Some((lo, hi)) = range.to_byte_bounds(&scan) else {
            return Ok(MapIter::empty());
        };
        let inner = r.raw_range(table, lo, hi)?;
        Ok(MapIter {
            inner,
            scan_len: scan.len(),
            _marker: PhantomData,
        })
    }

    /// Lazy, double-ended iterator over `(key, value)` pairs matching prefix `p`.
    pub fn prefix(&self, r: &impl Read, p: impl PrefixOf<K>) -> Result<MapIter<K, T>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_prefix::<K>(prefix, p);
        let inner = r.raw_range(table, lo, hi)?;
        Ok(MapIter {
            inner,
            scan_len: scan.len(),
            _marker: PhantomData,
        })
    }

    /// Cursor-paginated `(key, value)` entries: returns `(items, next_cursor)`.
    pub fn page<Q: KeyLookup<K>>(
        &self,
        r: &impl Read,
        after: Option<Q>,
        limit: usize,
        dir: Dir,
    ) -> Result<(Vec<(K, T)>, Option<K>)>
    where
        K: Clone,
    {
        if limit == 0 {
            return Ok((Vec::new(), None));
        }
        let mut items: Vec<(K, T)> = match (dir, after) {
            (Dir::Asc, None) => self.range(r, ..)?.take(limit + 1).collect::<Result<_>>()?,
            (Dir::Asc, Some(k)) => self
                .range(r, (Bound::Excluded(k), Bound::Unbounded))?
                .take(limit + 1)
                .collect::<Result<_>>()?,
            (Dir::Desc, None) => self
                .range(r, ..)?
                .rev()
                .take(limit + 1)
                .collect::<Result<_>>()?,
            (Dir::Desc, Some(k)) => self
                .range(r, (Bound::Unbounded, Bound::Excluded(k)))?
                .rev()
                .take(limit + 1)
                .collect::<Result<_>>()?,
        };
        let has_more = items.len() > limit;
        if has_more {
            items.truncate(limit);
        }
        let next = if has_more {
            items.last().map(|(k, _)| k.clone())
        } else {
            None
        };
        Ok((items, next))
    }

    /// All `(key, value)` pairs in sorted key order.
    pub fn iter(&self, r: &impl Read) -> Result<Vec<(K, T)>> {
        self.range(r, ..)?.collect()
    }

    /// Rewrite every value in the map inside `tx`: `Some(new)` updates, `None`
    /// deletes.
    pub fn transform_values(
        &self,
        tx: &mut Tx,
        mut f: impl FnMut(&K, T) -> Option<T>,
    ) -> Result<()> {
        let items = self.iter(tx)?;
        for (k, v) in items {
            match f(&k, v) {
                Some(next) => self.key(&k).set(tx, &next)?,
                None => {
                    self.key(&k).delete(tx)?;
                }
            }
        }
        Ok(())
    }
}

