//! Typed paths: composable, zero-I/O addresses into a durable schema.
//!
//! A [`Path<S>`] carries its `redb` table location plus a phantom schema type
//! `S`. Navigation methods are gated by `S` so illegal paths fail to compile.
//!
//! - Reads take `&impl Read` (`&ReadTx` for snapshot-consistent streaming reads,
//!   `&Tx` for read-your-writes inside a reducer, or `&Db` for one-offs).
//! - Mutations take `&mut Tx` and execute atomically in arrival order.

use std::borrow::Cow;
use std::marker::PhantomData;
use std::ops::Bound;

use serde::{de::DeserializeOwned, Serialize};

use crate::key::{ByteBounds, Key, KeyLookup, KeyRange, PrefixOf};
use crate::schema::{decode_sum, encode_sum, Deque, Leaf, List, Map, Schema, Set, Sum, Summable};
use crate::store::{Read, StoreRange, Tx, SCALARS_TABLE};
use crate::watch::WatchRange;
use crate::{codec, decode_value, encode_value, Error, Result};

/// Direction for cursor pagination (`page` / `page_keys`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Dir {
    /// Ascending key order (`after` yields keys strictly `> after`).
    Asc,
    /// Descending key order (`after` yields keys strictly `< after`).
    Desc,
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum PathLoc {
    /// Root of a store (optional namespace prefix for table names).
    Root(Option<Cow<'static, str>>),
    /// A key prefix inside a concrete `redb` table (`prefix` empty = whole table).
    Table {
        table: Cow<'static, str>,
        prefix: Vec<u8>,
    },
}

/// A typed address into a durable schema.
///
/// Cheap to clone; carries only its table location and key prefix. Construct
/// the root of a schema via `MyStore::root()` (generated by `#[derive(Durable)]`),
/// then navigate with schema-specific methods.
pub struct Path<S> {
    loc: PathLoc,
    _schema: PhantomData<fn() -> S>,
}

impl<S> Clone for Path<S> {
    fn clone(&self) -> Self {
        Self {
            loc: self.loc.clone(),
            _schema: PhantomData,
        }
    }
}

impl<S> std::fmt::Debug for Path<S> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Path")
            .field("schema", &std::any::type_name::<S>())
            .field("loc", &self.loc)
            .finish()
    }
}

impl<S: Schema> Path<S> {
    /// The root of a schema (one root per database).
    pub fn root() -> Self {
        Self {
            loc: PathLoc::Root(None),
            _schema: PhantomData,
        }
    }

    /// A root namespaced under `name`, isolating tables as `"{name}/{field}"`.
    pub fn namespaced(name: &str) -> Self {
        Self {
            loc: PathLoc::Root(Some(Cow::Owned(name.to_string()))),
            _schema: PhantomData,
        }
    }
}

impl<S> Path<S> {
    pub(crate) fn in_table(table: Cow<'static, str>, prefix: Vec<u8>) -> Self {
        Self {
            loc: PathLoc::Table { table, prefix },
            _schema: PhantomData,
        }
    }

    /// The `redb` table name this path addresses, or `None` at a schema root.
    pub fn table(&self) -> Option<&str> {
        match &self.loc {
            PathLoc::Root(_) => None,
            PathLoc::Table { table, .. } => Some(table.as_ref()),
        }
    }

    /// The key prefix bytes within [`Path::table`], or empty at a table/schema root.
    pub fn prefix_bytes(&self) -> &[u8] {
        match &self.loc {
            PathLoc::Root(_) => &[],
            PathLoc::Table { prefix, .. } => prefix.as_slice(),
        }
    }

    /// The [`WatchRange`] covering every key at or under this path.
    pub fn watch_range(&self) -> WatchRange {
        match &self.loc {
            PathLoc::Root(None) => WatchRange::all(),
            PathLoc::Root(Some(ns)) => WatchRange::namespace(ns.as_ref()),
            PathLoc::Table { table, prefix } if prefix.is_empty() => {
                WatchRange::table(table.as_ref())
            }
            PathLoc::Table { table, prefix } => WatchRange::prefix(table.as_ref(), prefix),
        }
    }

    fn table_and_prefix(&self) -> (&str, &[u8]) {
        match &self.loc {
            PathLoc::Table { table, prefix } => (table.as_ref(), prefix.as_slice()),
            PathLoc::Root(_) => {
                panic!("durable: cannot perform table I/O directly on a schema root")
            }
        }
    }

    fn child<S2>(&self, seg: &[u8]) -> Path<S2> {
        let (table, prefix) = match &self.loc {
            PathLoc::Table { table, prefix } => (table.clone(), prefix.as_slice()),
            PathLoc::Root(_) => {
                panic!("durable: child key navigation requires a collection field, not root")
            }
        };
        Path::in_table(table, codec::child_key(prefix, seg))
    }

    /// Navigate to a `#[derive(Durable)]` struct field. Called by generated code.
    #[doc(hidden)]
    pub fn child_field<S2: Schema>(&self, field_name: &'static str, field_id: u32) -> Path<S2> {
        match &self.loc {
            PathLoc::Root(ns) => {
                if S2::IS_SCALAR {
                    let table = match ns {
                        None => Cow::Borrowed(SCALARS_TABLE),
                        Some(ns) => Cow::Owned(format!("{ns}/{SCALARS_TABLE}")),
                    };
                    let mut key = Vec::new();
                    codec::encode_escaped_bytes(field_name.as_bytes(), &mut key);
                    Path::in_table(table, key)
                } else {
                    let table = match ns {
                        None => Cow::Borrowed(field_name),
                        Some(ns) => Cow::Owned(format!("{ns}/{field_name}")),
                    };
                    Path::in_table(table, Vec::new())
                }
            }
            PathLoc::Table { table, prefix } => {
                let seg = codec::field_segment(field_id);
                Path::in_table(table.clone(), codec::child_key(prefix, &seg))
            }
        }
    }

    /// Delete everything at or under this path (scalar, collection, nested
    /// `#[derive(Durable)]` struct, namespace, or all app tables at root).
    ///
    /// On top-level collections (`prefix` empty), this drops the `redb` table
    /// in O(1). On nested subtrees, it removes the range in-place via `retain_in`.
    pub fn clear(&self, tx: &mut Tx) -> Result<()> {
        match &self.loc {
            PathLoc::Root(None) => tx.raw_wipe_app(),
            PathLoc::Root(Some(ns)) => tx.raw_wipe_namespace(ns.as_ref()),
            PathLoc::Table { table, prefix } => tx.raw_delete_prefix(table.as_ref(), prefix),
        }
    }

    /// Whether any key exists at or under this path (one seek).
    pub fn exists(&self, r: &impl Read) -> Result<bool> {
        let (table, prefix) = self.table_and_prefix();
        if prefix.is_empty() {
            return Ok(r.raw_table_len(table)? > 0);
        }
        let lo = Bound::Included(prefix.to_vec());
        let hi = match codec::prefix_upper_bound(prefix) {
            Some(u) => Bound::Excluded(u),
            None => Bound::Unbounded,
        };
        Ok(r.raw_first_in(table, lo, hi)?.is_some())
    }
}

fn scan_bounds_all(prefix: &[u8]) -> ByteBounds {
    let scan = codec::child_scan_prefix(prefix);
    let lo = if scan.is_empty() {
        Bound::Unbounded
    } else {
        Bound::Included(scan.clone())
    };
    let hi = match codec::prefix_upper_bound(&scan) {
        Some(u) => Bound::Excluded(u),
        None => Bound::Unbounded,
    };
    (lo, hi)
}

fn scan_bounds_prefix<K: Key>(parent: &[u8], p: impl PrefixOf<K>) -> ByteBounds {
    let mut scan = codec::child_scan_prefix(parent);
    p.encode_prefix(&mut scan);
    let lo = if scan.is_empty() {
        Bound::Unbounded
    } else {
        Bound::Included(scan.clone())
    };
    let hi = match codec::prefix_upper_bound(&scan) {
        Some(u) => Bound::Excluded(u),
        None => Bound::Unbounded,
    };
    (lo, hi)
}

