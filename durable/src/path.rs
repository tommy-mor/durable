impl<K: Key, V: Schema> Path<Map<K, V>> {
    /// Navigate to the sub-schema stored under `key`.
    ///
    /// Accepts owned keys, references, and borrowed forms (e.g. `"alice"` for
    /// `Map<String, _>`, `("github", "alice")` for `Map<(String, String), _>`).
    pub fn key(&self, key: impl KeyLookup<K>) -> Path<V> {
        let encoded = key.to_key_bytes();
        self.child(&encoded)
    }

    /// Delete `key` and its entire subtree inside `tx` (works for both flat
    /// `Leaf`/`Sum` values and nested structs/maps/lists).
    pub fn remove(&self, tx: &mut Tx, key: impl KeyLookup<K>) -> Result<()> {
        let child = self.key(key);
        if V::IS_FLAT {
            let (table, k) = child.table_and_prefix();
            tx.raw_delete(table, k)?;
            Ok(())
        } else {
            child.clear(tx)
        }
    }

    /// Whether `key` is present (one point get for flat maps, one seek for nested).
    pub fn contains(&self, r: &impl Read, key: impl KeyLookup<K>) -> Result<bool> {
        let child = self.key(key);
        if V::IS_FLAT {
            let (table, k) = child.table_and_prefix();
            Ok(r.raw_get(table, k)?.is_some())
        } else {
            child.exists(r)
        }
    }

    /// Whether the map has no entries (O(1) at root, one seek when nested).
    pub fn is_empty(&self, r: &impl Read) -> Result<bool> {
        let (table, prefix) = self.table_and_prefix();
        if prefix.is_empty() {
            return Ok(r.raw_table_len(table)? == 0);
        }
        let (lo, hi) = scan_bounds_all(prefix);
        Ok(r.raw_first_in(table, lo, hi)?.is_none())
    }

    /// Number of distinct keys in the map.
    ///
    /// O(1) on root flat maps (`Map<K, Leaf<T>>` / `Map<K, Sum<N>>` at a
    /// top-level struct field); key-only non-decoding scan otherwise.
    pub fn len(&self, r: &impl Read) -> Result<u64> {
        let (table, prefix) = self.table_and_prefix();
        if V::IS_FLAT && prefix.is_empty() {
            return r.raw_table_len(table);
        }
        self.count_range(r, ..)
    }

    /// Alias for [`Self::len`].
    pub fn count(&self, r: &impl Read) -> Result<u64> {
        self.len(r)
    }

    /// Count distinct keys matching `range` without decoding values.
    pub fn count_range(&self, r: &impl Read, range: impl KeyRange<K>) -> Result<u64> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let Some((lo, hi)) = range.to_byte_bounds(&scan) else {
            return Ok(0);
        };
        if V::IS_FLAT {
            return r.raw_count_in(table, lo, hi);
        }
        // Nested values: deduplicate logical keys without decoding them.
        let iter = r.raw_range(table, lo, hi)?;
        let scan_len = scan.len();
        let mut count = 0u64;
        let mut last: Option<Vec<u8>> = None;
        for item in iter {
            let (db_key, _) = item?;
            let rest = &db_key[scan_len..];
            let (_, used) = K::decode_key(rest)?;
            let seg = &rest[..used];
            if last.as_deref() != Some(seg) {
                last = Some(seg.to_vec());
                count += 1;
            }
        }
        Ok(count)
    }

    /// Smallest key in the map (one seek).
    pub fn first(&self, r: &impl Read) -> Result<Option<K>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_first_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (k, _) = K::decode_key(&db_key[scan.len()..])?;
                Ok(Some(k))
            }
            None => Ok(None),
        }
    }

    /// Largest key in the map (one reverse seek).
    pub fn last(&self, r: &impl Read) -> Result<Option<K>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_last_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (k, _) = K::decode_key(&db_key[scan.len()..])?;
                Ok(Some(k))
            }
            None => Ok(None),
        }
    }

    /// Lazy, double-ended iterator over keys in `range`.
    pub fn keys_range(&self, r: &impl Read, range: impl KeyRange<K>) -> Result<KeyIter<K>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let Some((lo, hi)) = range.to_byte_bounds(&scan) else {
            return Ok(KeyIter::empty());
        };
        let inner = r.raw_range(table, lo, hi)?;
        Ok(KeyIter::new(inner, scan.len(), !V::IS_FLAT))
    }

    /// Lazy, double-ended iterator over `(key, Path<V>)` entries in `range`.
    pub fn entries_range(&self, r: &impl Read, range: impl KeyRange<K>) -> Result<EntryIter<K, V>> {
        let keys = self.keys_range(r, range)?;
        let (table, parent_prefix) = match &self.loc {
            PathLoc::Table { table, prefix } => (table.clone(), prefix.clone()),
            PathLoc::Root(_) => unreachable!(),
        };
        Ok(EntryIter {
            keys,
            table,
            parent_prefix,
            _val: PhantomData,
        })
    }

    /// Lazy, double-ended iterator over keys matching prefix `p`
    /// (string prefix `"tom"` or composite tuple prefix `("github",)`).
    pub fn prefix_keys(&self, r: &impl Read, p: impl PrefixOf<K>) -> Result<KeyIter<K>> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_prefix::<K>(prefix, p);
        let inner = r.raw_range(table, lo, hi)?;
        Ok(KeyIter::new(inner, scan.len(), !V::IS_FLAT))
    }

    /// Lazy, double-ended iterator over `(key, Path<V>)` entries matching prefix `p`.
    pub fn prefix_entries(&self, r: &impl Read, p: impl PrefixOf<K>) -> Result<EntryIter<K, V>> {
        let keys = self.prefix_keys(r, p)?;
        let (table, parent_prefix) = match &self.loc {
            PathLoc::Table { table, prefix } => (table.clone(), prefix.clone()),
            PathLoc::Root(_) => unreachable!(),
        };
        Ok(EntryIter {
            keys,
            table,
            parent_prefix,
            _val: PhantomData,
        })
    }

    /// Cursor-paginated keys: returns `(page_keys, next_cursor)`.
    ///
    /// `next_cursor` is `Some(last_key)` only when at least one more entry
    /// exists beyond this page.
    pub fn page_keys<Q: KeyLookup<K>>(
        &self,
        r: &impl Read,
        after: Option<Q>,
        limit: usize,
        dir: Dir,
    ) -> Result<(Vec<K>, Option<K>)>
    where
        K: Clone,
    {
        if limit == 0 {
            return Ok((Vec::new(), None));
        }
        let mut items: Vec<K> = match (dir, after) {
            (Dir::Asc, None) => self
                .keys_range(r, ..)?
                .take(limit + 1)
                .collect::<Result<_>>()?,
            (Dir::Asc, Some(k)) => self
                .keys_range(r, (Bound::Excluded(k), Bound::Unbounded))?
                .take(limit + 1)
                .collect::<Result<_>>()?,
            (Dir::Desc, None) => self
                .keys_range(r, ..)?
                .rev()
                .take(limit + 1)
                .collect::<Result<_>>()?,
            (Dir::Desc, Some(k)) => self
                .keys_range(r, (Bound::Unbounded, Bound::Excluded(k)))?
                .rev()
                .take(limit + 1)
                .collect::<Result<_>>()?,
        };
        let has_more = items.len() > limit;
        if has_more {
            items.truncate(limit);
        }
        let next = if has_more { items.last().cloned() } else { None };
        Ok((items, next))
    }

    /// All keys in sorted key order.
    pub fn keys(&self, r: &impl Read) -> Result<Vec<K>> {
        self.keys_range(r, ..)?.collect()
    }

    /// All `(key, Path<V>)` pairs in sorted key order.
    pub fn entries(&self, r: &impl Read) -> Result<Vec<(K, Path<V>)>> {
        self.entries_range(r, ..)?.collect()
    }
}

