/// Lazy, double-ended iterator over distinct logical keys in a [`Map`] or [`Set`].
///
/// On a [`crate::ReadTx`], this streams pages directly from `redb` without
/// materializing the range into memory.
pub struct KeyIter<K> {
    inner: StoreRange,
    scan_len: usize,
    dedup: bool,
    last_front: Option<Vec<u8>>,
    last_back: Option<Vec<u8>>,
    done: bool,
    _key: PhantomData<K>,
}

impl<K: Key> KeyIter<K> {
    fn empty() -> Self {
        Self {
            inner: StoreRange::empty(),
            scan_len: 0,
            dedup: false,
            last_front: None,
            last_back: None,
            done: true,
            _key: PhantomData,
        }
    }

    fn new(inner: StoreRange, scan_len: usize, dedup: bool) -> Self {
        Self {
            inner,
            scan_len,
            dedup,
            last_front: None,
            last_back: None,
            done: false,
            _key: PhantomData,
        }
    }

    fn decode_item(&mut self, db_key: Vec<u8>, from_front: bool) -> Result<Option<K>> {
        if db_key.len() < self.scan_len {
            return Err(Error::Corruption("key shorter than scan prefix".into()));
        }
        let rest = &db_key[self.scan_len..];
        let (k, used) = K::decode_key(rest)?;
        if !self.dedup {
            if used != rest.len() {
                return Err(Error::Corruption("unexpected trailing bytes in flat key".into()));
            }
            return Ok(Some(k));
        }
        let seg = &rest[..used];
        if from_front {
            if self.last_back.as_deref() == Some(seg) {
                self.done = true;
                return Ok(None);
            }
            if self.last_front.as_deref() == Some(seg) {
                return Ok(None);
            }
            self.last_front = Some(seg.to_vec());
        } else {
            if self.last_front.as_deref() == Some(seg) {
                self.done = true;
                return Ok(None);
            }
            if self.last_back.as_deref() == Some(seg) {
                return Ok(None);
            }
            self.last_back = Some(seg.to_vec());
        }
        Ok(Some(k))
    }
}

impl<K: Key> Iterator for KeyIter<K> {
    type Item = Result<K>;

    fn next(&mut self) -> Option<Self::Item> {
        while !self.done {
            let item = self.inner.next()?;
            match item {
                Err(e) => return Some(Err(e)),
                Ok((db_key, _)) => match self.decode_item(db_key, true) {
                    Ok(Some(k)) => return Some(Ok(k)),
                    Ok(None) => continue,
                    Err(e) => return Some(Err(e)),
                },
            }
        }
        None
    }
}

impl<K: Key> DoubleEndedIterator for KeyIter<K> {
    fn next_back(&mut self) -> Option<Self::Item> {
        while !self.done {
            let item = self.inner.next_back()?;
            match item {
                Err(e) => return Some(Err(e)),
                Ok((db_key, _)) => match self.decode_item(db_key, false) {
                    Ok(Some(k)) => return Some(Ok(k)),
                    Ok(None) => continue,
                    Err(e) => return Some(Err(e)),
                },
            }
        }
        None
    }
}

/// Lazy, double-ended iterator yielding `(K, Path<V>)` pairs for any [`Map<K, V>`].
pub struct EntryIter<K, V> {
    keys: KeyIter<K>,
    table: Cow<'static, str>,
    parent_prefix: Vec<u8>,
    _val: PhantomData<fn() -> V>,
}

impl<K: Key, V: Schema> Iterator for EntryIter<K, V> {
    type Item = Result<(K, Path<V>)>;

    fn next(&mut self) -> Option<Self::Item> {
        self.keys.next().map(|res| {
            res.map(|k| {
                let seg = k.to_key_bytes();
                let path = Path::in_table(
                    self.table.clone(),
                    codec::child_key(&self.parent_prefix, &seg),
                );
                (k, path)
            })
        })
    }
}

impl<K: Key, V: Schema> DoubleEndedIterator for EntryIter<K, V> {
    fn next_back(&mut self) -> Option<Self::Item> {
        self.keys.next_back().map(|res| {
            res.map(|k| {
                let seg = k.to_key_bytes();
                let path = Path::in_table(
                    self.table.clone(),
                    codec::child_key(&self.parent_prefix, &seg),
                );
                (k, path)
            })
        })
    }
}

/// Lazy, double-ended iterator yielding `(K, T)` pairs for a `Map<K, Leaf<T>>`.
pub struct MapIter<K, T> {
    inner: StoreRange,
    scan_len: usize,
    _marker: PhantomData<(K, T)>,
}

impl<K: Key, T: DeserializeOwned> MapIter<K, T> {
    fn empty() -> Self {
        Self {
            inner: StoreRange::empty(),
            scan_len: 0,
            _marker: PhantomData,
        }
    }

    fn decode_pair(&self, db_key: Vec<u8>, db_val: Vec<u8>) -> Result<(K, T)> {
        if db_key.len() < self.scan_len {
            return Err(Error::Corruption("key shorter than scan prefix".into()));
        }
        let rest = &db_key[self.scan_len..];
        let (k, used) = K::decode_key(rest)?;
        if used != rest.len() {
            return Err(Error::Corruption("unexpected nested key in leaf map".into()));
        }
        let v = decode_value(&db_val)?;
        Ok((k, v))
    }
}

impl<K: Key, T: DeserializeOwned> Iterator for MapIter<K, T> {
    type Item = Result<(K, T)>;

    fn next(&mut self) -> Option<Self::Item> {
        self.inner.next().map(|res| {
            let (k, v) = res?;
            self.decode_pair(k, v)
        })
    }
}

impl<K: Key, T: DeserializeOwned> DoubleEndedIterator for MapIter<K, T> {
    fn next_back(&mut self) -> Option<Self::Item> {
        self.inner.next_back().map(|res| {
            let (k, v) = res?;
            self.decode_pair(k, v)
        })
    }
}

