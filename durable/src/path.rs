impl<T: Serialize + DeserializeOwned + 'static> Path<Deque<Leaf<T>>> {
    /// Number of elements (O(1) at root; O(log N) two seeks when nested).
    pub fn len(&self, r: &impl Read) -> Result<u64> {
        let (table, prefix) = self.table_and_prefix();
        if prefix.is_empty() {
            return r.raw_table_len(table);
        }
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        let Some((first_key, _)) = r.raw_first_in(table, lo.clone(), hi.clone())? else {
            return Ok(0);
        };
        let Some((last_key, _)) = r.raw_last_in(table, lo, hi)? else {
            return Ok(0);
        };
        let (head, _) = i64::decode_key(&first_key[scan.len()..])?;
        let (tail, _) = i64::decode_key(&last_key[scan.len()..])?;
        Ok((tail - head + 1).max(0) as u64)
    }

    /// Read the front element without removing it (one seek).
    pub fn front(&self, r: &impl Read) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_first_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Read the back element without removing it (one reverse seek).
    pub fn back(&self, r: &impl Read) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match r.raw_last_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Push `value` to the back inside `tx`.
    pub fn push_back(&self, tx: &mut Tx, value: &T) -> Result<()> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        let next_idx = match tx.raw_last_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (tail, _) = i64::decode_key(&db_key[scan.len()..])?;
                tail + 1
            }
            None => 0,
        };
        self.child::<Leaf<T>>(&codec::order_i64(next_idx))
            .set(tx, value)
    }

    /// Push `value` to the front inside `tx`.
    pub fn push_front(&self, tx: &mut Tx, value: &T) -> Result<()> {
        let (table, prefix) = self.table_and_prefix();
        let scan = codec::child_scan_prefix(prefix);
        let (lo, hi) = scan_bounds_all(prefix);
        let next_idx = match tx.raw_first_in(table, lo, hi)? {
            Some((db_key, _)) => {
                let (head, _) = i64::decode_key(&db_key[scan.len()..])?;
                head - 1
            }
            None => 0,
        };
        self.child::<Leaf<T>>(&codec::order_i64(next_idx))
            .set(tx, value)
    }

    /// Remove and return the front element inside `tx`.
    pub fn pop_front(&self, tx: &mut Tx) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match tx.raw_pop_first_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Remove and return the back element inside `tx`.
    pub fn pop_back(&self, tx: &mut Tx) -> Result<Option<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        match tx.raw_pop_last_in(table, lo, hi)? {
            Some((_, v)) => Ok(Some(decode_value(&v)?)),
            None => Ok(None),
        }
    }

    /// Drop elements from the back until the length is at most `max_len` inside `tx`.
    pub fn truncate_back(&self, tx: &mut Tx, max_len: u64) -> Result<()> {
        let mut len = self.len(tx)?;
        while len > max_len {
            if self.pop_back(tx)?.is_none() {
                break;
            }
            len -= 1;
        }
        Ok(())
    }

    /// Drop elements from the front until the length is at most `max_len` inside `tx`
    /// (ideal for capped "most recent N" windows where new items are pushed to the back).
    pub fn truncate_front(&self, tx: &mut Tx, max_len: u64) -> Result<()> {
        let mut len = self.len(tx)?;
        while len > max_len {
            if self.pop_front(tx)?.is_none() {
                break;
            }
            len -= 1;
        }
        Ok(())
    }

    /// Lazy, double-ended iterator from front to back.
    pub fn range(&self, r: &impl Read) -> Result<SeqIter<T>> {
        let (table, prefix) = self.table_and_prefix();
        let (lo, hi) = scan_bounds_all(prefix);
        let inner = r.raw_range(table, lo, hi)?;
        Ok(SeqIter {
            inner,
            _marker: PhantomData,
        })
    }

    /// All elements from front to back (single streaming range scan).
    pub fn iter(&self, r: &impl Read) -> Result<Vec<T>> {
        self.range(r)?.collect()
    }
}
